export const dictionaries: Record<Lang, Record<Key, string>> = { en, af };

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  let text = dictionaries[lang][key] ?? en[key] ?? key;
  if (text.includes("|") && typeof vars.n === "number") {
    const [one, many] = text.split("|");
    text = vars.n === 1 ? one : many;
  } else if (text.includes("|")) {
    text = text.split("|")[1];
  }
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}
